export function normalizeQuestion(question: string): string {
  return question
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9+]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const EXEMPLAR_NORMALIZED = new Set(
  Object.values(INTENT_EXEMPLARS).flatMap((list) => list.map(normalizeQuestion)),
);

export function isInExemplarBank(question: string): boolean {
  return EXEMPLAR_NORMALIZED.has(normalizeQuestion(question));
}

export function exemplarCount(id: ClassifiedIntentId): number {
  return INTENT_EXEMPLARS[id]?.length ?? 0;
}
